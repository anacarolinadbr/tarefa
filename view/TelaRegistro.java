public void carregarTabela() {

    String sql = "SELECT idTarefa, tarefa, andamento FROM tarefa";

    try (Connection conn = Conexao.conectar();
         PreparedStatement stmt = conn.prepareStatement(sql);
         ResultSet rs = stmt.executeQuery()) {

        DefaultTableModel model = (DefaultTableModel) tabelaTarefa.getModel();
        model.setRowCount(0);

        while (rs.next()) {

            int id = rs.getInt("idTarefa");
            String tarefa = rs.getString("tarefa");
            String andamento = rs.getString("andamento");

            model.addRow(new Object[]{id, tarefa, andamento});
        }

    } catch (Exception e) {
        e.printStackTrace();
    }
}
    
    
