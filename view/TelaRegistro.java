    private void btnNextActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnNextActionPerformed
        
    int linha = tabelaTarefa.getSelectedRow();

    if (linha == -1) {
        JOptionPane.showMessageDialog(this, "Selecione uma tarefa primeiro");
        return;
    }

    int idTarefa = (int) tabelaTarefa.getValueAt(linha, 0);
    String andamentoAtual = tabelaTarefa.getValueAt(linha, 2).toString();

    String novoStatus = "";

    if (andamentoAtual.equals("Pendente")) {
        novoStatus = "Fazendo";
    } 
    else if (andamentoAtual.equals("Fazendo")) {
        novoStatus = "Concluído";
    } 
    else {
        JOptionPane.showMessageDialog(this, "Tarefa já concluída");
        return;
    }

    String sql = "UPDATE tarefa SET andamento = ? WHERE idTarefa = ?";

    try (Connection conn = Conexao.conectar();
         PreparedStatement stmt = conn.prepareStatement(sql)) {

        stmt.setString(1, novoStatus);
        stmt.setInt(2, idTarefa);

        stmt.executeUpdate();

    } catch (Exception e) {
        e.printStackTrace();
    }

    carregarTabela(); // atualiza a tabela
    }//GEN-LAST:event_btnNextActionPerformed

